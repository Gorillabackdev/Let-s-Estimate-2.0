export function getStateByName(name?: string): (NigerianStateData & { costIndex: number; isSwamp: boolean; terrain: string }) | undefined {
  if (!name) return undefined;
  const clean = name.trim().toLowerCase();
  const s = NIGERIAN_STATES.find(
    (item) => item.name.toLowerCase() === clean || item.name.toLowerCase().includes(clean) || clean.includes(item.name.toLowerCase())
  );
  if (!s) return undefined;
  const isSwamp = s.defaultTerrain === 'Swamp' || s.defaultTerrain === 'Waterlogged' || s.defaultTerrain === 'Coastal';
  return {
    ...s,
    costIndex: s.regionalCostIndex,
    isSwamp,
    terrain: s.defaultTerrain,
  };
}

export const ALL_NIGERIAN_STATES = NIGERIAN_STATES;
export const getNigerianStateData = getStateByName;

export function getRegionalFactorForLocation(location?: string, stateName?: string): number {
  if (stateName) {
    const s = getStateByName(stateName);
    if (s) return s.regionalCostIndex;
  }
  if (location) {
    const s = getStateByName(location);
    if (s) return s.regionalCostIndex;
  }
  return 1.00;
}
